import { describe, expect, it } from 'vitest'
import type { Context } from '@deepseek-ai/cordis'

import { registerPlanSettings } from '../src/dsh/settings'

interface SettingsHarness {
  ctx: Context
  fiber: unknown
  presentations: Array<{ policy: { auto?: boolean }; owner: unknown }>
  warnings: string[]
}

/** Build a host context that records the settings page policy. */
function makeSettingsHarness(fail = false): SettingsHarness {
  const presentations: Array<{ policy: { auto?: boolean }; owner: unknown }> = []
  const warnings: string[] = []
  const fiber = { id: 'plan-store-fiber' }
  const ctx = {
    fiber,
    logger: { warn: (message: string) => warnings.push(message) },
    effect: (factory: () => () => void) => factory(),
    settings: {
      configure(policy: { auto?: boolean }, owner: unknown) {
        if (fail) throw new Error('Settings presentation is already configured for this plugin instance')
        presentations.push({ policy, owner })
        return () => {}
      },
    },
  } as unknown as Context
  return { ctx, fiber, presentations, warnings }
}

describe('settings page policy', () => {
  it('configures an autogenerated page owned by the plugin fiber', () => {
    const settings = makeSettingsHarness()
    registerPlanSettings(settings.ctx)

    expect(settings.presentations).toHaveLength(1)
    expect(settings.presentations[0]?.policy).toEqual({ auto: true })
    expect(settings.presentations[0]?.owner).toBe(settings.fiber)
    expect(settings.warnings).toHaveLength(0)
  })

  it('warns instead of failing when the policy is taken', () => {
    const settings = makeSettingsHarness(true)
    expect(() => registerPlanSettings(settings.ctx)).not.toThrow()
    expect(settings.warnings[0]).toContain('was not registered')
  })
})
